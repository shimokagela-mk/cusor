/**
 * 扫描 ref/gf_tdoll_data 目录，生成 frontend/tdoll-data.js
 * 供 formation.html 引用
 *
 * 用法: node scripts/generate_tdoll_data.js
 */
const fs = require('fs');
const path = require('path');

const REF_ROOT = path.resolve(__dirname, '../../../ref/gf_tdoll_data');
const OUT_FILE = path.resolve(__dirname, '../frontend/tdoll-data.js');

// 枪种目录映射：目录名前缀 → 枪种代码
const TYPE_DIRS = [
  { dir: '01_HG_手枪', code: 'HG' },
  { dir: '02_SMG_冲锋枪', code: 'SMG' },
  { dir: '03_RF_步枪', code: 'RF' },
  { dir: '04_AR_突击步枪', code: 'AR' },
  { dir: '05_MG_机枪', code: 'MG' },
  { dir: '06_SG_霰弹枪', code: 'SG' },
];

// 从目录名解析人形名称和星级
// 格式: "M4A1_★★★★" → { name: 'M4A1', stars: 4 }
function parseDirName(dirName) {
  const idx = dirName.lastIndexOf('_');
  if (idx === -1) return { name: dirName, stars: 0 };
  const name = dirName.substring(0, idx);
  const starStr = dirName.substring(idx + 1);
  const stars = (starStr.match(/★/g) || []).length;
  return { name, stars };
}

// 检查默认立绘文件是否存在，返回相对 frontend 的路径
function findDefaultPortrait(tdollDir, typeDir, tdollDirName) {
  const portraitDir = path.join(tdollDir, '01_立绘展示', '默认立绘');
  if (!fs.existsSync(portraitDir)) return null;

  const files = fs.readdirSync(portraitDir);
  // 优先 HD 版本，非 damaged
  const hdNormal = files.find(f => f.endsWith('_HD.png') && !f.includes('_D_'));
  const normal = files.find(f => f.endsWith('.png') && !f.includes('_D_') && !f.endsWith('_HD.png'));

  const fileName = hdNormal || normal;
  if (!fileName) return null;

  // 相对路径: 从 frontend/ 到 奶龙王一键制卡/ref/gf_tdoll_data/.../01_立绘展示/默认立绘/xxx.png
  // frontend/ → 少女前线/ → projects/ → 奶龙王一键制卡/ → ref/
  return `../../../ref/gf_tdoll_data/${typeDir}/${tdollDirName}/01_立绘展示/默认立绘/${fileName}`;
}

function main() {
  const tdolls = [];
  const warnings = [];

  for (const { dir: typeDir, code: typeCode } of TYPE_DIRS) {
    const typePath = path.join(REF_ROOT, typeDir);
    if (!fs.existsSync(typePath)) {
      warnings.push(`目录不存在: ${typePath}`);
      continue;
    }

    const entries = fs.readdirSync(typePath, { withFileTypes: true });
    for (const entry of entries) {
      if (!entry.isDirectory()) continue;

      const tdollDirName = entry.name;
      const tdollDir = path.join(typePath, tdollDirName);
      const { name, stars } = parseDirName(tdollDirName);

      // 读取基本信息
      const infoFile = path.join(tdollDir, '03_基本信息.json');
      let info = {};
      if (fs.existsSync(infoFile)) {
        try { info = JSON.parse(fs.readFileSync(infoFile, 'utf8')); }
        catch (e) { warnings.push(`解析失败: ${infoFile} - ${e.message}`); }
      }

      // 读取属性数据
      const statsFile = path.join(tdollDir, '04_属性数据.json');
      let stats = {};
      if (fs.existsSync(statsFile)) {
        try { stats = JSON.parse(fs.readFileSync(statsFile, 'utf8')); }
        catch (e) { warnings.push(`解析失败: ${statsFile} - ${e.message}`); }
      }

      // 查找默认立绘
      const portrait = findDefaultPortrait(tdollDir, typeDir, tdollDirName);

      tdolls.push({
        name: info['名称'] || name,
        type: typeCode,
        stars: stars || parseInt(info['星级'] || '0', 10),
        canMod: info['心智升级'] === '有',
        cv: info['CV'] || '',
        artist: info['画师'] || '',
        hp: stats['生命'] || 0,
        damage: stats['伤害'] || 0,
        accuracy: stats['命中'] || 0,
        evasion: stats['回避'] || 0,
        rof: stats['射速'] || 0,
        armor: stats['护甲'] || 0,
        movement: stats['移动'] || 0,
        armorPiercing: stats['穿甲'] || 0,
        critRate: stats['暴击'] || 0,
        ammoChain: stats['弹链'] || 0,
        portrait: portrait || '',
      });
    }
  }

  // 按枪种排序、同枪种按星级降序
  const typeOrder = { HG: 0, SMG: 1, RF: 2, AR: 3, MG: 4, SG: 5 };
  tdolls.sort((a, b) => {
    const ta = typeOrder[a.type] ?? 9;
    const tb = typeOrder[b.type] ?? 9;
    if (ta !== tb) return ta - tb;
    if (b.stars !== a.stars) return b.stars - a.stars;
    return a.name.localeCompare(b.name);
  });

  // 生成 JS 文件
  const jsContent = [
    '// Auto-generated by scripts/generate_tdoll_data.js',
    '// DO NOT EDIT MANUALLY - run `node scripts/generate_tdoll_data.js` to regenerate',
    `// Generated at: ${new Date().toISOString()}`,
    '// Source: ref/gf_tdoll_data/',
    '',
    'var TDOLL_DATA = ' + JSON.stringify(tdolls, null, 2) + ';',
  ].join('\n');

  fs.writeFileSync(OUT_FILE, jsContent, 'utf8');

  console.log(`✓ Generated ${tdolls.length} tdolls → ${path.relative(process.cwd(), OUT_FILE)}`);
  if (warnings.length) {
    console.log(`\nWarnings (${warnings.length}):`);
    warnings.slice(0, 20).forEach(w => console.log('  - ' + w));
    if (warnings.length > 20) console.log(`  ... and ${warnings.length - 20} more`);
  }
  const noPortrait = tdolls.filter(t => !t.portrait).length;
  if (noPortrait) {
    console.log(`\nNote: ${noPortrait} tdolls without default portrait`);
  }
}

main();
